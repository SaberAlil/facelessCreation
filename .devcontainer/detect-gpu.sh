#!/usr/bin/env bash
# Runs on the HOST (VS Code "initializeCommand") before the containers start.
# Read-only checks; the only thing it writes is .devcontainer/compose.local.yaml
# (git-ignored), which turns GPU passthrough on or off.
#
# Force CPU mode:  FACELESS_FORCE_CPU=1 code .
set -euo pipefail

cd "$(dirname "$0")"
out="compose.local.yaml"
mode="cpu"
reason=""

if [ "${FACELESS_FORCE_CPU:-0}" = "1" ]; then
  reason="FACELESS_FORCE_CPU=1"
elif ! command -v nvidia-smi >/dev/null 2>&1; then
  reason="nvidia-smi not found on the host (no NVIDIA driver?)"
elif ! nvidia-smi -L >/dev/null 2>&1; then
  reason="nvidia-smi could not talk to the NVIDIA driver"
elif ! { command -v nvidia-ctk >/dev/null 2>&1 \
         || command -v nvidia-container-cli >/dev/null 2>&1 \
         || [[ "$(docker info --format '{{json .Runtimes}}' 2>/dev/null)" == *nvidia* ]]; }; then
  reason="NVIDIA Container Toolkit not found"
else
  mode="gpu"
fi

if [ "$mode" = "gpu" ]; then
  {
    echo "# GENERATED by detect-gpu.sh - GPU mode. Do not edit; do not commit."
    cat compose.gpu.yaml
  } > "$out"
  echo "[detect-gpu] GPU mode: $(nvidia-smi --query-gpu=name --format=csv,noheader | head -1)"
else
  cat > "$out" <<EOF
# GENERATED by detect-gpu.sh - CPU fallback mode. Do not edit; do not commit.
# Reason: ${reason}
services:
  dev: {}
EOF
  echo "[detect-gpu] CPU fallback mode: ${reason}"
fi
