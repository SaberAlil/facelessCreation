PROCEDURAL_LICENSE = "Original work generated by Faceless Studio (owned by the channel)"


def _from_library(a: LibraryAsset, scene_id: str, lib_dir: Path, reason: str,
                  candidates: list[str]) -> SceneAsset:
    path = lib_dir / a.path
    if not path.is_file():
        raise FacelessError(f"library file missing for {a.id}: {path}")
    return SceneAsset(
        scene_id=scene_id, kind=a.kind if a.kind in ("video", "image") else "image",
        library_id=a.id, path=str(path), sha256=a.sha256, source_url=a.source_url,
        creator=a.creator, license=a.license, attribution=a.attribution,
        attribution_required=a.attribution_required, commercial_use=a.commercial_use,
        provider=a.provider, ai_generated=a.ai_generated, rights=RightsStatus.UNREVIEWED,
        candidates=candidates, reason=reason,
    )


def procedural_asset(s: Settings, paths: JobPaths, scene_index: int, scene_id: str,
                     overlay: str, title: str | None, reason: str) -> SceneAsset:
    g = plan_graphic(scene_index, overlay, title)
    out = paths.assets_dir / "generated" / f"{scene_id}.png"
    render_graphic(g, out, s.font_file(), s.render.width, s.render.height)
    return SceneAsset(
        scene_id=scene_id, kind="procedural", path=str(out.relative_to(paths.root)),
        sha256=sha256_file(out), template=f"{g.template}/p{g.palette}",
        license=PROCEDURAL_LICENSE, commercial_use=True, provider="procedural",
        rights=RightsStatus.CONFIRMED, reason=reason,
    )


def build_manifest(s: Settings, db: Database, paths: JobPaths, script: Script,
                   use_pexels: bool = False, keep_existing: bool = True,
                   ai_images: bool = False, comfy_transport=None) -> tuple[AssetManifest, dict]:
    previous = load_manifest(paths) if keep_existing else None
    prev_by_scene = {a.scene_id: a for a in previous.scenes} if previous else {}
    pool = [a for a in library.list_assets(db) if a.kind in ("video", "image")
            and a.commercial_use]
    used: set[str] = set()
    pexels = None
    stats = {"library": 0, "pexels": 0, "procedural": 0, "kept": 0, "ai": 0,
             "pexels_errors": [], "ai_errors": []}
    if use_pexels:
        from .providers.stock import PexelsProvider
        pexels = PexelsProvider(s.stock)
    comfy = None
    if ai_images:
        from .providers.images import ComfyUIProvider
        comfy = ComfyUIProvider(s.comfyui, s.resources, s.locks_dir,
                                s.resolve(s.comfyui.workflow), transport=comfy_transport)
    scenes_out: list[SceneAsset] = []
    for i, sc in enumerate(script.scenes):
        prev = prev_by_scene.get(sc.id)
        # Keep manual choices (and anything still valid) unless the user rebuilds.
        if prev and prev.reason.startswith("manual") and _still_valid(prev, paths):
            scenes_out.append(prev)
            if prev.library_id:
                used.add(prev.library_id)
            stats["kept"] += 1
            continue
        ranked = sorted(((library.score(a, sc.search_terms, sc.visual), a) for a in pool
                         if a.id not in used), key=lambda t: -t[0])
        cands = [a.id for sc_, a in ranked[: s.stock.per_scene_candidates] if sc_ > 0]
        if ranked and ranked[0][0] > 0:
            best = ranked[0][1]
            used.add(best.id)
            scenes_out.append(_from_library(best, sc.id, s.library_dir,
                                            f"auto: matched {ranked[0][0]} terms", cands))
            stats["library"] += 1
            continue
        if pexels and sc.search_terms:
            try:
                got = _pexels_pick(s, db, pexels, sc.search_terms, used)
            except FacelessError as e:
                stats["pexels_errors"].append(f"{sc.id}: {e}")
                got = None
            if got:
                used.add(got.id)
                scenes_out.append(_from_library(got, sc.id, s.library_dir,
                                                "auto: pexels search", []))
                stats["pexels"] += 1
                continue
        if comfy is not None:
            try:
                got = _ai_image(s, db, comfy, paths, sc)
                used.add(got.id)
                scenes_out.append(_from_library(got, sc.id, s.library_dir,
                                                "auto: AI illustration (ComfyUI)", []))
                stats["ai"] += 1
                continue
            except FacelessError as e:  # OOM twice, timeout, unreachable: use graphics
                stats["ai_errors"].append(f"{sc.id}: {e}")
        scenes_out.append(procedural_asset(
            s, paths, i, sc.id, sc.overlay, script.title if i == 0 else None,
            "auto: no matching licensed asset; original graphic"))
        stats["procedural"] += 1
    manifest = AssetManifest(scenes=scenes_out, music=previous.music if previous else None)
    save_manifest(paths, manifest)
    return manifest, stats


def _pexels_pick(s: Settings, db: Database, pexels, terms: list[str], used: set[str]
                 ) -> LibraryAsset | None:
    for term in terms[:2]:
        for cand in pexels.search(term, per_page=s.stock.per_scene_candidates + 2):
            dest = s.cache_dir / "pexels" / f"pexels-{cand['id']}.mp4"
            if not dest.is_file():
                pexels.download(cand, dest)
            from .providers.stock import PEXELS_LICENSE, PEXELS_LICENSE_URL
            a = library.add_asset(
                db, s.library_dir, dest, license=PEXELS_LICENSE, license_url=PEXELS_LICENSE_URL,
                commercial_use=True, source_url=cand["page_url"], creator=cand["creator"],
                attribution=f"Video by {cand['creator']} on Pexels", provider="pexels",
                tags=term.split(), title=f"pexels {cand['id']}", move=True)
            if a.id not in used:
                return a
    return None


def _ai_image(s: Settings, db: Database, comfy, paths: JobPaths, sc) -> LibraryAsset:
    from .util import hash_obj
    seed = int(hash_obj([paths.root.name, sc.id, sc.visual])[:8], 16)
    prompt = ", ".join(x for x in [sc.visual, *sc.search_terms[:3],
                                   "editorial illustration, clean composition, soft light, "
                                   "vertical frame, no text"] if x)
    out = s.cache_dir / "comfyui" / f"{paths.root.name}-{sc.id}-{seed}.png"
    res = comfy.generate(prompt, out, seed)
    return library.add_asset(
        db, s.library_dir, res.path, move=True, provider="comfyui", ai_generated=True,
        license=f"AI-generated with {res.model} ({s.comfyui.checkpoint_license})",
        commercial_use=True, creator="Faceless Studio (ComfyUI)", title=f"ai {sc.id}",
        tags=sc.search_terms,
        notes=json.dumps({"model": res.model, "seed": res.seed, "width": res.width,
                          "height": res.height, "steps": res.steps, "prompt": res.prompt,
                          "prompt_id": res.prompt_id, "oom_retry": res.retried_after_oom}))


def _still_valid(a: SceneAsset, paths: JobPaths) -> bool:
    p = Path(a.path) if Path(a.path).is_absolute() else paths.root / a.path
    return p.is_file() and sha256_file(p) == a.sha256


def load_manifest(paths: JobPaths) -> AssetManifest | None:
    if not paths.manifest.is_file():
        return None
    return AssetManifest.model_validate(read_json(paths.manifest))


def save_manifest(paths: JobPaths, m: AssetManifest) -> None:
    write_json(paths.manifest, m.model_dump(mode="json"))


def asset_file(paths: JobPaths, a: SceneAsset) -> Path:
    p = Path(a.path)
    return p if p.is_absolute() else paths.root / p


def replace_scene_asset(s: Settings, db: Database, paths: JobPaths, script: Script,
                        scene_id: str, library_id: str | None = None,
                        procedural: bool = False, overlay: str | None = None) -> AssetManifest:
    m = load_manifest(paths)
    if m is None:
        raise FacelessError("no asset manifest yet; run 'faceless assets JOB' first")
    idx = next((i for i, a in enumerate(m.scenes) if a.scene_id == scene_id), None)
    if idx is None:
        raise FacelessError(f"no scene {scene_id}; scenes: {[a.scene_id for a in m.scenes]}")
    if library_id:
        a = library.get_asset(db, library_id)
        if a.kind not in ("video", "image"):
            raise FacelessError(f"{library_id} is {a.kind}, not a picture")
        if not a.commercial_use:
            raise FacelessError(f"{library_id} is not cleared for commercial use")
        m.scenes[idx] = _from_library(a, scene_id, s.library_dir, f"manual: {utcnow()}", [])
    elif procedural:
        sc = next(x for x in script.scenes if x.id == scene_id)
        new = procedural_asset(s, paths, idx, scene_id, overlay if overlay is not None
                               else sc.overlay, None, f"manual: {utcnow()}")
        m.scenes[idx] = new
    else:
        raise FacelessError("give --use LIBRARY_ID or --procedural")
    save_manifest(paths, m)
    return m


def set_music(s: Settings, db: Database, paths: JobPaths, library_id: str | None
              ) -> AssetManifest:
    m = load_manifest(paths)
    if m is None:
        raise FacelessError("no asset manifest yet")
    if library_id is None:
        m.music = None
    else:
        a = library.get_asset(db, library_id)
        if a.kind != "audio":
            raise FacelessError(f"{library_id} is not audio")
        if not a.commercial_use:
            raise FacelessError("music must be cleared for commercial, cross-platform use")
        m.music = SceneAsset(
            scene_id="music", kind="audio", library_id=a.id, path=str(s.library_dir / a.path),
            sha256=a.sha256, source_url=a.source_url, creator=a.creator, license=a.license,
            attribution=a.attribution, attribution_required=a.attribution_required,
            commercial_use=True, provider=a.provider, rights=RightsStatus.UNREVIEWED,
            reason=f"manual: {utcnow()}")
    save_manifest(paths, m)
    return m


def set_rights(paths: JobPaths, scene_ids: list[str] | None, status: RightsStatus
               ) -> AssetManifest:
    """Record the human rights decision for scenes (None = all, including music)."""
    m = load_manifest(paths)
    if m is None:
        raise FacelessError("no asset manifest yet")
    items = m.scenes + ([m.music] if m.music else [])
    known = {a.scene_id for a in items}
    if scene_ids:
        unknown = set(scene_ids) - known
        if unknown:
            raise FacelessError(f"unknown scene ids {sorted(unknown)}")
    for a in items:
        if scene_ids is None or a.scene_id in scene_ids:
            a.rights = status
    save_manifest(paths, m)
    return m


def asset_problems(paths: JobPaths, m: AssetManifest, script: Script) -> list[str]:
    out = []
    ids = [sc.id for sc in script.scenes]
    if [a.scene_id for a in m.scenes] != ids:
        out.append("manifest scenes do not match the script; re-run 'faceless assets'")
    items = m.scenes + ([m.music] if m.music else [])
    for a in items:
        if not a.commercial_use:
            out.append(f"{a.scene_id}: not cleared for commercial use")
        if not a.license:
            out.append(f"{a.scene_id}: no license recorded")
        if a.rights != RightsStatus.CONFIRMED:
            out.append(f"{a.scene_id}: rights {a.rights.value}")
        if a.attribution_required and not a.attribution:
            out.append(f"{a.scene_id}: attribution required but missing")
        if not _still_valid(a, paths):
            out.append(f"{a.scene_id}: file missing or changed since selection")
    backgrounds = [a.sha256 for a in m.scenes]
    if len(backgrounds) > 2 and len(set(backgrounds)) == 1:
        out.append("every scene uses the same visual")
    return out
